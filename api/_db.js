import { neon } from '@neondatabase/serverless';

const databaseUrl = process.env.DATABASE_URL;
const sql = databaseUrl ? neon(databaseUrl) : null;

let initializationPromise;

function requireDatabase() {
  if (!sql) {
    throw new Error('DATABASE_URL is not configured.');
  }
  return sql;
}

export function initializeDatabase() {
  if (!initializationPromise) {
    initializationPromise = (async () => {
      const db = requireDatabase();

      await db`
        CREATE TABLE IF NOT EXISTS projects (
          id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          title        TEXT NOT NULL CHECK (length(trim(title)) > 0),
          status       TEXT NOT NULL CHECK (status IN ('active', 'completed', 'on_hold')),
          deadline     DATE,
          budget       NUMERIC NOT NULL CHECK (budget >= 0),
          spent_amount NUMERIC NOT NULL CHECK (spent_amount >= 0),
          created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          seed_key     INTEGER UNIQUE
        )
      `;

      // seed_key makes initialization safe when multiple serverless instances
      // start at the same time. User-created projects always leave it null.
      await db`
        INSERT INTO projects
          (title, status, deadline, budget, spent_amount, seed_key)
        VALUES
          ('E-Commerce Website Redesign', 'active', '2026-12-15', 120000, 45000, 1),
          ('Brand Identity for Startup', 'completed', '2026-10-20', 50000, 50000, 2),
          ('Mobile App for Fitness Tracking', 'active', '2026-11-20', 180000, 200000, 3),
          ('Internal HR Dashboard', 'on_hold', '2026-09-30', 90000, 12000, 4),
          ('Portfolio Website', 'active', NULL, 25000, 30000, 5)
        ON CONFLICT (seed_key) DO NOTHING
      `;
    })().catch((error) => {
      initializationPromise = undefined;
      throw error;
    });
  }

  return initializationPromise;
}

const PROJECT_COLUMNS = `
  id,
  title,
  status,
  TO_CHAR(deadline, 'YYYY-MM-DD') AS deadline,
  budget::DOUBLE PRECISION AS budget,
  spent_amount::DOUBLE PRECISION AS "spentAmount",
  created_at AS "createdAt"
`;

export async function listProjects(status) {
  const db = requireDatabase();

  if (status) {
    return db.query(
      `SELECT ${PROJECT_COLUMNS}
       FROM projects
       WHERE status = $1
       ORDER BY deadline IS NULL, deadline ASC, id ASC`,
      [status]
    );
  }

  return db.query(
    `SELECT ${PROJECT_COLUMNS}
     FROM projects
     ORDER BY deadline IS NULL, deadline ASC, id ASC`
  );
}

export async function insertProject(project) {
  const db = requireDatabase();
  const rows = await db.query(
    `INSERT INTO projects (title, status, deadline, budget, spent_amount)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING ${PROJECT_COLUMNS}`,
    [project.title, project.status, project.deadline, project.budget, project.spentAmount]
  );
  return rows[0];
}

export async function changeProjectStatus(id, status) {
  const db = requireDatabase();
  const rows = await db.query(
    `UPDATE projects
     SET status = $1
     WHERE id = $2
     RETURNING ${PROJECT_COLUMNS}`,
    [status, id]
  );
  return rows[0] ?? null;
}
